from dialogue_parse import dat, loc
cases = [
 ("மதுரை", "மதுரைக்கு", "மதுரையில்"),
 ("திருச்சி", "திருச்சிக்கு", "திருச்சியில்"),
 ("அண்ணா நகர்", "அண்ணா நகருக்கு", None),
 ("தெப்பக்குளம்", "தெப்பக்குளத்துக்கு", "தெப்பக்குளத்தில்"),
 ("விமான நிலையம்", "விமான நிலையத்துக்கு", "விமான நிலையத்தில்"),
 ("மீனாட்சி அம்மன் கோவில்", "மீனாட்சி அம்மன் கோவிலுக்கு", None),
 ("சென்னை", "சென்னைக்கு", "சென்னையில்"),
]
bad = 0
for name, d, l in cases:
    gd, gl = dat(name), loc(name)
    ok = gd == d and (l is None or gl == l)
    bad += not ok
    print("OK  " if ok else "FAIL", name, "| dat:", gd, "| loc:", gl)
print("failures:", bad)